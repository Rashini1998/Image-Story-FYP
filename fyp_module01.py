class MarkovChain:
    def __init__(self):
        self.model = {}

    def build_model(self, tokens):
        for i in range(len(tokens) - 1):
            current_word = tokens[i]
            next_word = tokens[i + 1]
            if current_word not in self.model:
                self.model[current_word] = {}
            if next_word not in self.model[current_word]:
                self.model[current_word][next_word] = 0
            self.model[current_word][next_word] += 1

    def get_next_word(self, current_word, image_features):
        next_words = self.model.get(current_word, {})
        if not next_words:
            return None

        feature_weight = 0.1
        modified_next_words = {}

        # Initialize brightness_value
        brightness_value = 0

        # Adjust weights based on image_features if it's a list of dictionaries
        if isinstance(image_features, list):
            for feature in image_features:
                if 'brightness' in feature:
                    brightness_value += feature['brightness']

        # Calculate the average brightness if there are multiple features
        if len(image_features) > 0:
            brightness_value /= len(image_features)

        for word, count in next_words.items():
            # Example adjustment based on brightness_value
            count += brightness_value * 0.05  # Adjust count based on brightness

            modified_next_words[word] = count + feature_weight

        total = sum(modified_next_words.values())
        rand_val = random.uniform(0, total)
        cumulative = 0
        for word, count in modified_next_words.items():
            cumulative += count
            if rand_val <= cumulative:
                return word

        return None

# Generate the story using the Markov chain model and image features
def generate_story(markov_chain, start_word, image_features, length=100):
    current_word = start_word
    sentence = [current_word]
    for _ in range(length - 1):
        next_word = markov_chain.get_next_word(current_word, image_features)
        if next_word is None:
            break
        sentence.append(next_word)
        current_word = next_word
    return ' '.join(sentence)

# Define a function to perform image recognition
def perform_image_recognition(image_folder):
    features_list = []
    for image_file in os.listdir(image_folder):
        if image_file.endswith(('.png', '.jpg', '.jpeg')):
            image_path = os.path.join(image_folder, image_file)
            img_resnet = cv2.imread(image_path)

            if img_resnet is None:
                print(f"Error: Image '{image_file}' failed to load.")
                continue

            # Resize the image to fit ResNet50 input size
            img_resnet = cv2.resize(img_resnet, (224, 224))
            img_array_resnet = preprocess_input(np.expand_dims(img_resnet, axis=0))

            # Use ResNet50 to predict object classes
            predictions_resnet = model_resnet.predict(img_array_resnet)

            # Extract features from predictions
            features = extract_features(predictions_resnet)

            # Append the features to the list
            features_list.append(features)

    return features_list

# Define a function to extract features from ResNet50 predictions
def extract_features(predictions_resnet):
    # Flatten the predictions to get a single feature vector
    feature_vector = predictions_resnet.flatten()
    return feature_vector

